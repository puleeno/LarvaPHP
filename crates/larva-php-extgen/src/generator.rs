use std::io::Write;
use std::path::Path;

use crate::config::{ExtGenConfig, ExtensionMeta};

/// Generate Rust FFI bindings from C source files.
pub fn generate(config: &ExtGenConfig) -> std::io::Result<()> {
    // Collect source files
    let source_files = collect_source_files(&config.source_dir)?;

    for file in &source_files {
        tracing::debug!("Processing {:?}", file);
        // TODO: parse C source and extract function/class info
    }

    // Generate bindgen bindings
    generate_bindgen(config)?;

    // Generate wrapper code
    generate_wrappers(config)?;

    Ok(())
}

fn collect_source_files(dir: &Path) -> std::io::Result<Vec<std::path::PathBuf>> {
    let mut files = Vec::new();

    if !dir.exists() {
        return Ok(files);
    }

    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_file() {
            if let Some(ext) = path.extension() {
                if matches!(ext.to_str(), Some("c") | Some("h") | Some("cpp") | Some("hpp")) {
                    files.push(path);
                }
            }
        } else if path.is_dir() {
            files.extend(collect_source_files(&path)?);
        }
    }

    Ok(files)
}

fn generate_bindgen(config: &ExtGenConfig) -> std::io::Result<()> {
    // Use bindgen to generate FFI bindings
    let output = config.output_file.as_path();

    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent)?;
    }

    // TODO: Actually run bindgen
    let mut file = std::fs::File::create(output)?;
    writeln!(file, "// Auto-generated by larva-php-extgen. Do not edit.")?;
    writeln!(file)?;
    writeln!(file, "#![allow(non_camel_case_types)]")?;
    writeln!(file, "#![allow(non_upper_case_globals)]")?;
    writeln!(file, "#![allow(non_snake_case)]")?;
    writeln!(file)?;

    Ok(())
}

